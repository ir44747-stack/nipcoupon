/**
 * build-analytics.js — bundle src/analytics.js into assets/analytics.js
 *
 * @vercel/analytics ships ESM/CJS for bundlers. This project deliberately has
 * no bundler for the app itself (index.html is hand-written, and minify.js
 * only *transforms* — it never resolves a bare import like '@vercel/analytics').
 * Dropping `import` straight into the page would therefore 404 in the browser.
 *
 * So we do the one thing that actually needs a bundler, and only that: resolve
 * the package into a single self-contained IIFE that a plain <script> can load.
 * The output is committed, so a deploy never depends on node_modules being
 * present or on esbuild resolving at build time on Vercel.
 *
 * Idempotent: writes only when the bytes change, so it cannot create noisy
 * diffs on every build the way a timestamped banner would.
 *
 *   node scripts/build-analytics.js            write assets/analytics.js
 *   node scripts/build-analytics.js --check    verify it is up to date (CI)
 */
'use strict';

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const ENTRY = path.join(ROOT, 'src', 'analytics.js');
const OUT = path.join(ROOT, 'assets', 'analytics.js');
const CHECK = process.argv.includes('--check');

let esbuild;
try {
  esbuild = require('esbuild');
} catch (e) {
  /* No esbuild (e.g. a production install with --omit=dev). The committed
     asset is already correct, so this is not a failure — regenerating is only
     needed when src/analytics.js or the package version changes. */
  console.log('analytics  esbuild unavailable — keeping committed assets/analytics.js');
  process.exit(0);
}

if (!fs.existsSync(ENTRY)) {
  console.error('analytics  missing ' + path.relative(ROOT, ENTRY));
  process.exit(1);
}

let result;
try {
  result = esbuild.buildSync({
    entryPoints: [ENTRY],
    bundle: true,
    minify: true,
    format: 'iife',
    target: ['es2019'],
    platform: 'browser',
    legalComments: 'none',
    write: false
  });
} catch (e) {
  console.error('analytics  bundle failed: ' + e.message);
  process.exit(1);
}

const banner =
  '/* Vercel Web Analytics — generated by scripts/build-analytics.js from ' +
  'src/analytics.js. Do not edit by hand; run `npm run build:analytics`. */\n';
const next = banner + result.outputFiles[0].text;

const prev = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : null;

if (CHECK) {
  if (prev !== next) {
    console.error('analytics  assets/analytics.js is STALE — run: npm run build:analytics');
    process.exit(1);
  }
  console.log('analytics  assets/analytics.js is up to date');
  process.exit(0);
}

if (prev === next) {
  console.log('analytics  assets/analytics.js unchanged (' + Buffer.byteLength(next) + ' B)');
} else {
  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, next);
  console.log('analytics  wrote assets/analytics.js (' + Buffer.byteLength(next) + ' B)');
}
